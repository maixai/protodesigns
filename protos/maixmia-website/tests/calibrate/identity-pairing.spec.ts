for (const manual of [false, true]) {
  test(`添加 Agent:${manual ? '10 位手动码' : '一次性链接'}完整配对`, async ({ page }, testInfo) => {
    const issues: string[] = []
    page.on('pageerror', (error) => issues.push(error.message))
    page.on('console', (message) => { if (message.type() === 'error') issues.push(message.text()) })
    page.on('requestfailed', (request) => issues.push(request.url()))
    page.on('response', (response) => { if (response.status() >= 400) issues.push(`${response.status()} ${response.url()}`) })
    await page.setViewportSize({ width: 1280, height: 900 })
    await login(page)
    await openPairing(page)
    await pairDemoAgent(page, manual ? '手动连接助手' : '链接连接助手', '我的自有主机', false, manual)
    await expect(page.locator('.agent-context-switcher__trigger')).toContainText(manual ? '手动连接助手' : '链接连接助手')
    await page.locator('.agent-context-switcher__trigger').click()
    await expect(page.locator('.agent-context-switcher__option')).toHaveCount(4)
    await expect(page.locator('.agent-context-switcher__option').last()).toContainText('我的自有主机')
    await page.screenshot({ path: testInfo.outputPath(`paired-${manual ? 'code' : 'link'}.png`) })
    expect(issues).toEqual([])
  })
}

