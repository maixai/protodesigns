for (const width of [375, 768, 1280, 1600]) {
  test(`配对与模拟 Agent 端:深色、多宽度无横向溢出 @${width}`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 900 })
    await login(page)
    await openPairing(page)
    await generateInvitation(page)
    const dialog = page.getByTestId('agent-pairing-dialog')
    await expect(dialog).toBeVisible()
    expect(await dialog.evaluate((element) => element.scrollWidth - element.clientWidth)).toBeLessThanOrEqual(1)
    expect(await page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth)).toBeLessThanOrEqual(0)
    const colors = await dialog.evaluate((element) => ({ background: getComputedStyle(element).backgroundColor, text: getComputedStyle(element).color }))
    expect(colors.background).not.toBe('rgb(255, 255, 255)')
    expect(colors.background).not.toBe(colors.text)
    await page.screenshot({ path: testInfo.outputPath(`pairing-manual-dark-${width}.png`) })
    await page.getByTestId('mock-agent-open-link').click()
    await expect(page.getByRole('checkbox', { name: '安全码一致', exact: true })).toBeVisible()
    expect(await dialog.evaluate((element) => element.scrollWidth - element.clientWidth)).toBeLessThanOrEqual(1)
    await page.screenshot({ path: testInfo.outputPath(`pairing-review-dark-${width}.png`) })
  })
}
