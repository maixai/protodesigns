import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
import { pairDemoAgent, unlockDemoIdentity } from './identity-helpers'

test.use({ locale: 'zh-CN', reducedMotion: 'reduce' })
async function login(page: Page, unlock = true): Promise<void> {
  await page.goto('/')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  if (unlock) await unlockDemoIdentity(page)
}
async function openPairing(page: Page): Promise<void> {
  if ((page.viewportSize()?.width ?? 1280) < 1024) await page.getByRole('button', { name: '打开侧栏', exact: true }).click()
  await page.locator('.agent-context-switcher__trigger').click()
  await page.getByRole('button', { name: '添加 Agent', exact: true }).click()
  await expect(page.getByTestId('agent-pairing-dialog')).toBeVisible()
}
async function generateInvitation(page: Page): Promise<void> {
  await page.getByRole('button', { name: '没有正在运行的 Agent？打开模拟 Agent 端', exact: true }).click()
  await page.getByTestId('mock-agent-panel').getByRole('button', { name: '生成配对邀请', exact: true }).click()
  await expect(page.getByTestId('mock-agent-code')).toHaveValue(/^[A-Z0-9]{5}-[A-Z0-9]{5}$/)
}
async function approveBrowser(page: Page): Promise<void> {
  await page.getByRole('checkbox', { name: '安全码一致', exact: true }).check()
  await page.getByRole('button', { name: '用 Passkey 确认并添加', exact: true }).click()
  await page.getByTestId('mock-pairing-passkey').click()
  await expect(page.getByTestId('mock-agent-allow')).toBeVisible()
}

