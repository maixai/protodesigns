import { flushPromises, mount } from '@vue/test-utils'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { NSwitch } from 'naive-ui'
import ProjectPluginsPanel from '../../src/components/project-plugins-panel.vue'
import AgentPlugins from '../../src/components/agent-plugins.vue'
import { mockAgentSummaries, mockInstalledPlugins, mockProjects } from '../../src/mocks/workspace'
import { useI18n } from '../../src/i18n'
import * as api from '../../src/api/workspace'
import * as toolsApi from '../../src/api/project-tools'
vi.mock('../../src/mocks/delay', () => ({ delay: async () => {} }))

const agent = mockAgentSummaries()[0]
const project = agent ? mockProjects(agent.id)[0] : undefined
if (!agent || !project) throw new Error('Missing project plugin fixtures')
beforeEach(() => { useI18n().setLocale('zh-CN'); document.body.innerHTML = ''; vi.restoreAllMocks() })

describe('project-plugins-panel', () => {
  it('waits for inherited data before consuming a requested plugin destination', async () => {
    const wrapper = mount(ProjectPluginsPanel, { props: { agent, project, requestedPluginKey: 'browser-tools@community' }, attachTo: document.body })
    await flushPromises()
    expect(wrapper.get('.plugin-detail').text()).toContain('Browser Tools')
    expect(wrapper.emitted('openRequestConsumed')).toHaveLength(1)
    wrapper.unmount()
  })
  it('retains inherited rows when the project source fails without presenting a guessed effective state', async () => {
    const request = vi.spyOn(toolsApi, 'getProjectToolOverrides').mockResolvedValueOnce({ ok: false, error: new Error('Project unavailable') })
    const wrapper = mount(ProjectPluginsPanel, { props: { agent, project }, attachTo: document.body })
    await flushPromises()
    expect(wrapper.text()).toContain('Browser Tools')
    expect(wrapper.text()).toContain('本项目来源加载失败')
    expect(wrapper.getComponent(NSwitch).props('disabled')).toBe(true)
    const retry = wrapper.get('.plugin-source-error button')
    expect(retry.text()).toBe('重试')
    await retry.trigger('click')
    await flushPromises()
    expect(request).toHaveBeenCalledTimes(2)
    expect(wrapper.find('.plugin-source-error').exists()).toBe(false)
    expect(wrapper.findAll('.compact-plugin')).toHaveLength(4)
    wrapper.unmount()
  })
  it('preserves the previous effective value and reports a scoped error when an immediate operation fails', async () => {
    vi.spyOn(toolsApi, 'setProjectToolOverride').mockResolvedValue({ ok: false, error: new Error('Host unavailable') })
    const wrapper = mount(ProjectPluginsPanel, { props: { agent, project }, attachTo: document.body })
    await flushPromises()
    const toggle = wrapper.get('.compact-plugin:has([data-plugin-key="browser-tools@community"]) [role="switch"]')
    await toggle.trigger('click')
    await flushPromises()
    expect(toggle.attributes('aria-checked')).toBe('true')
    expect(wrapper.get('.plugin-error').text()).toContain('本项目「weekly-report」')
    expect(wrapper.get('.plugin-error').text()).toContain('Host unavailable')
    wrapper.unmount()
  })
  it('toggles project-owned installation state without creating an inherited override', async () => {
    const setEnabled = vi.spyOn(api, 'setPluginEnabled')
    const setOverride = vi.spyOn(toolsApi, 'setProjectToolOverride')
    const initial = await toolsApi.getProjectToolOverrides(project.path)
    const wrapper = mount(ProjectPluginsPanel, { props: { agent, project }, attachTo: document.body })
    await flushPromises()
    expect(wrapper.getComponent(AgentPlugins).props('embedded')).toBe(true)
    const row = wrapper.get('.compact-plugin:has([data-plugin-key="test-runner@anthropic"])')
    await row.get('[role="switch"]').trigger('click')
    await flushPromises()
    expect(setEnabled).toHaveBeenLastCalledWith('project', project.path, 'anthropic', 'test-runner', false)
    expect(row.text()).toContain('本项目已停用')
    expect(row.text()).not.toContain('覆盖')
    expect(row.find('.plugin-restore').exists()).toBe(false)
    await row.get('[role="switch"]').trigger('click')
    await flushPromises()
    expect(setEnabled).toHaveBeenLastCalledWith('project', project.path, 'anthropic', 'test-runner', true)
    expect(row.text()).toContain('本项目已启用')
    expect(setOverride).not.toHaveBeenCalled()
    expect(await toolsApi.getProjectToolOverrides(project.path)).toEqual(initial)
    wrapper.unmount()
  })
  it('shows both sources with one switch each, writes only the project override and restores it', async () => {
    const before = mockInstalledPlugins('agent', agent.id)
    const wrapper = mount(ProjectPluginsPanel, { props: { agent, project }, attachTo: document.body })
    await flushPromises()
    expect(wrapper.findAll('.compact-plugin')).toHaveLength(4)
    expect(wrapper.text()).toContain('本项目生效插件')
    const row = wrapper.get('.plugin-main[data-plugin-key="browser-tools@community"]').element.parentElement
    if (!row) throw new Error('Missing plugin row')
    const toggle = row.querySelector<HTMLElement>('[role="switch"]')
    toggle?.click()
    await flushPromises()
    expect(row.textContent).toContain('本项目已停用')
    expect(row.textContent).toContain('覆盖')
    expect(mockInstalledPlugins('agent', agent.id)).toEqual(before)
    const restore = row.querySelector<HTMLButtonElement>('.plugin-restore')
    expect(restore?.getAttribute('aria-label')).toContain('本项目「weekly-report」')
    restore?.click()
    await flushPromises()
    expect(row.textContent).toContain('本项目已启用')
    expect(wrapper.emitted('state')?.at(-1)?.[0]).toMatchObject({ dirty: false, canSave: false })
    wrapper.unmount()
  })
  it('makes inherited configuration read-only and forwards the exact Agent plugin destination', async () => {
    const wrapper = mount(ProjectPluginsPanel, { props: { agent, project }, attachTo: document.body })
    await flushPromises()
    await wrapper.get('.plugin-main[data-plugin-key="data-analysis@anthropic"]').trigger('click')
    expect(wrapper.get('.plugin-readonly').text()).toContain('定义由 Agent 管理')
    expect(wrapper.find('.plugin-detail input').exists()).toBe(false)
    expect(wrapper.find('.plugin-detail .plugin-danger').exists()).toBe(false)
    await wrapper.get('.plugin-readonly button').trigger('click')
    expect(wrapper.emitted('manageAgent')?.[0]).toEqual(['data-analysis@anthropic'])
    await wrapper.get('.agent-plugins').trigger('keydown', { key: 'Escape' })
    await flushPromises()
    expect(wrapper.getComponent(AgentPlugins).attributes('data-view')).toBe('list')
    wrapper.unmount()
  })
  it('saves only the project copy explicitly and guards leaving its dirty detail', async () => {
    const spy = vi.spyOn(api, 'savePluginConfig')
    const wrapper = mount(ProjectPluginsPanel, { props: { agent, project }, attachTo: document.body })
    await flushPromises()
    await wrapper.get('.plugin-main[data-plugin-key="test-runner@anthropic"]').trigger('click')
    const field = wrapper.find('[data-config-key="testCommand"]')
    const input = field.exists() ? field : wrapper.get('[data-config-control]')
    await input.setValue('pnpm test:project')
    expect(wrapper.emitted('state')?.at(-1)?.[0]).toMatchObject({ dirty: true, canSave: false })
    await wrapper.get('.plugin-back').trigger('click')
    expect(wrapper.get('.plugin-keep-editing').exists()).toBe(true)
    await wrapper.get('.plugin-keep-editing').trigger('click')
    await wrapper.get('.plugin-config').trigger('submit')
    await flushPromises()
    expect(spy).toHaveBeenCalledWith('project', project.path, 'anthropic', 'test-runner', expect.any(Array))
    expect(wrapper.emitted('state')?.at(-1)?.[0]).toMatchObject({ dirty: false })
    wrapper.unmount()
  })
  it('shows inherited marketplace registrations read-only and keeps installation project-scoped', async () => {
    const wrapper = mount(ProjectPluginsPanel, { props: { agent, project }, attachTo: document.body })
    await flushPromises()
    const community = wrapper.get('.market-row[data-marketplace="community"]')
    expect(community.text()).toContain('Agent 提供 · 只读')
    expect(community.find('.market-controls').exists()).toBe(false)
    await wrapper.get('.plugin-add').trigger('click')
    expect(wrapper.get('.plugin-install').text()).toContain('只安装到本项目「weekly-report」')
    expect(wrapper.findAll('.install-market option')).toHaveLength(3)
    wrapper.unmount()
  })
  it('keeps a project source visible when only the Agent source fails, with a source retry', async () => {
    const original = api.listInstalledPlugins
    vi.spyOn(api, 'listInstalledPlugins').mockImplementation(async (scope, owner) => scope === 'agent' ? { ok: false, error: new Error('Agent unavailable') } : original(scope, owner))
    const wrapper = mount(ProjectPluginsPanel, { props: { agent, project }, attachTo: document.body })
    await flushPromises()
    expect(wrapper.text()).toContain('Agent 来源加载失败')
    expect(wrapper.text()).toContain('Test Runner')
    expect(wrapper.get('.plugin-error button').text()).toBe('重试')
    wrapper.unmount()
  })
})
