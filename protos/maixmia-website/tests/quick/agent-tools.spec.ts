test('@area:agent-tools 失败的插件 MCP 可独立重连且焦点稳定', async ({ page }) => {
  const issues = collectRuntimeIssues(page)
  await page.setViewportSize({ width: 1280, height: 900 })
  await login(page)
  await waitForWorkspace(page)
  const { panel } = await openMcp(page)
  const row = panel.locator('[data-server-id="plugin:anthropic:data-analysis:data-analysis"]')
  const reconnect = panel.locator('.mcp-plugin-row .mcp-plugin-reconnect')
  await expect(reconnect).toHaveText('重连')
  await row.focus()
  await page.keyboard.press('Tab')
  await expect(reconnect).toBeFocused()
  await reconnect.click()
  await expect(panel.locator('.mcp-plugin-row .mcp-plugin-reconnect')).toHaveCount(0)
  await expect(row).toBeFocused()
  await expect(row.locator('..')).toHaveAttribute('data-status', 'connected')
  await expect(row.locator('.mcp-tools-count')).toHaveText('3 个工具')
  await row.click()
  await expect(panel.locator('.mcp-plugin-detail .mcp-tools')).toContainText('profile_dataset')
  expect(issues).toEqual([])
})

test('@area:agent-tools 异常行提供短原因 tooltip 且正常行保持安静', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await login(page)
  await waitForWorkspace(page)
  const { panel } = await openMcp(page)
  const tooltip = page.getByRole('tooltip')
  const sentry = panel.locator('[data-server-id="agent:planning:sentry"]')
  await sentry.hover()
  await expect(tooltip).toBeVisible()
  await expect(tooltip).toHaveText('认证后可恢复连接')
  await page.keyboard.press('Escape')
  await expect(tooltip).toBeHidden()
  await panel.locator('[data-server-id="agent:planning:postgres"]').hover()
  await expect(tooltip).toHaveText('Connection refused. Start PostgreSQL, then reconnect.')
  await page.keyboard.press('Escape')
  await panel.locator('[data-server-id="agent:planning:github"]').hover()
  await expect(tooltip).toBeHidden()
})

