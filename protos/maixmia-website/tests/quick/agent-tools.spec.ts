import { expect, test } from '@playwright/test'
import type { Locator, Page } from '@playwright/test'
import { collectRuntimeIssues, login, waitForWorkspace } from './helpers'

test.use({ locale: 'zh-CN', reducedMotion: 'reduce' })

async function openAgentSettings(page: Page): Promise<Locator> {
  await page.locator('.agent-context-switcher__trigger').click()
  await page.locator('.agent-context-switcher__settings').click()
  const dialog = page.getByRole('dialog', { name: 'Agent 设置', exact: true })
  await expect(dialog).toBeVisible()
  return dialog
}

async function openMcp(page: Page): Promise<{ dialog: Locator; panel: Locator }> {
  const dialog = await openAgentSettings(page)
  await dialog.getByRole('tab', { name: 'MCP', exact: true }).click()
  const panel = dialog.locator('.agent-mcp')
  return { dialog, panel }
}

async function expectVisibleStatus(locator: Locator): Promise<void> {
  await expect(locator.locator('.mcp-status-label')).toHaveText(/已连接|需认证|连接失败|已停用|插件已停用|需配置|连接中/)
}

test('@area:agent-tools 侧栏收敛后 Agent 设置承载五标签与即时 MCP 操作', async ({ page }) => {
  const issues = collectRuntimeIssues(page)
  await page.setViewportSize({ width: 1280, height: 900 })
  await login(page)
  await waitForWorkspace(page)
  await expect(page.locator('.workspace-projects [role="tablist"]')).toHaveCount(0)
  await expect(page.locator('.project-row__mcp')).toHaveCount(0)
  const { dialog, panel } = await openMcp(page)
  await expect(dialog.locator('.agent-editor__tabs').getByRole('tab')).toHaveText(['基本', '模型', '权限', '插件', 'MCP'])
  await expect(panel.locator('[data-group="manual"] .mcp-row')).toHaveCount(4)
  await expect(panel.locator('.mcp-plugin-row')).toHaveCount(2)
  const github = panel.locator('[data-server-id="agent:planning:github"]')
  await expect(github.locator('.mcp-status-label')).toHaveText('已连接')
  await expectVisibleStatus(github)
  const healthy = panel.locator('[data-server-id="plugin:community:browser-tools:browser"]')
  await expect(healthy).toContainText('来自 Browser Tools')
  await expect(healthy).toContainText('3 个工具')
  await expect(panel.locator('.mcp-plugin-row .mcp-switch')).toHaveCount(0)
  const sentry = panel.locator('[data-server-id="agent:planning:sentry"]')
  await panel.getByRole('button', { name: '认证「Sentry」', exact: true }).click()
  await expect(sentry.locator('..')).toHaveAttribute('data-status', 'connected')
  await expect(sentry).toBeFocused()
  await panel.getByRole('switch', { name: '停用「GitHub」', exact: true }).click()
  await expect(github.locator('..')).toHaveAttribute('data-status', 'disabled')
  await panel.getByRole('button', { name: '添加 MCP 服务器', exact: true }).first().click()
  await panel.locator('#agent-mcp-planning-name').fill('linear')
  await panel.locator('#agent-mcp-planning-endpoint').fill('npx -y @example/linear-mcp')
  await panel.getByRole('button', { name: '添加服务器', exact: true }).click()
  await expect(panel.locator('[data-group="manual"] .mcp-row')).toHaveCount(5)
  await expect(dialog.locator('.agent-editor__save-button')).toHaveCount(0)
  await expect(dialog.locator('.agent-editor__save-state')).toHaveCount(0)
  await expect(dialog.getByRole('button', { name: '关闭', exact: true })).toBeVisible()
  expect(issues).toEqual([])
})

