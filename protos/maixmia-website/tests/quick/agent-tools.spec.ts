test('@area:agent-settings 设置入口只在 MCP 需处理时显示可访问状态点', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await login(page)
  await waitForWorkspace(page)
  await page.locator('.agent-context-switcher__trigger').click()
  const settings = page.locator('.agent-context-switcher__settings')
  await expect(settings).toHaveAccessibleName('Agent 设置 · 有 MCP 需要处理')
  await expect(settings.locator('.agent-context-switcher__attention-dot')).toHaveAttribute('aria-hidden', 'true')
  await settings.click()
  const dialog = page.getByRole('dialog', { name: 'Agent 设置', exact: true })
  await dialog.getByRole('tab', { name: 'MCP', exact: true }).click()
  const panel = dialog.locator('.agent-mcp')
  await panel.getByRole('button', { name: '认证「Sentry」', exact: true }).click()
  await panel.getByRole('button', { name: '重连「PostgreSQL」', exact: true }).click()
  await panel.locator('.mcp-plugin-row .mcp-plugin-reconnect').click()
  await expect(panel.locator('[data-status="needsAuth"], [data-status="failed"]')).toHaveCount(0)
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  await page.locator('.agent-context-switcher__trigger').click()
  await expect(page.locator('.agent-context-switcher__settings')).toHaveAccessibleName('Agent 设置')
  await expect(page.locator('.agent-context-switcher__attention-dot')).toHaveCount(0)
})

test('@area:agent-tools 插件与 MCP 标签在 720px 及四档视口下不横向溢出', async ({ page }) => {
  const issues = collectRuntimeIssues(page)
  await page.setViewportSize({ width: 1280, height: 900 })
  await login(page)
  await waitForWorkspace(page)
  const dialog = await openAgentSettings(page)
  for (const width of [375, 768, 1280, 1600]) {
    await page.setViewportSize({ width, height: 900 })
    for (const tab of ['插件', 'MCP']) {
      await dialog.getByRole('tab', { name: tab, exact: true }).click()
      const body = dialog.locator('.agent-editor__body')
      await expect(body).toBeVisible()
      expect(await body.evaluate((element) => element.scrollWidth - element.clientWidth)).toBeLessThanOrEqual(1)
    }
  }
  expect(issues).toEqual([])
})
