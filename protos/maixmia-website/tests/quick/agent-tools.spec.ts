test('@area:agent-tools 安装插件按市场筛选、分页且列表独立滚动', async ({ page }) => {
  const issues = collectRuntimeIssues(page)
  await page.setViewportSize({ width: 1280, height: 900 })
  await login(page)
  await waitForWorkspace(page)
  const { dialog, panel } = await openInstall(page)
  const market = panel.getByRole('combobox', { name: '筛选插件市场', exact: true })
  await expect(market).toBeVisible()
  await market.selectOption('community')
  const rows = panel.locator('.install-row')
  await expect(rows.first()).toBeVisible()
  expect(await rows.evaluateAll((elements) => elements.every((element) => element.getAttribute('data-marketplace') === 'community'))).toBe(true)
  // 安装操作贴住行尾内容缘,并与整行垂直居中;不再独占一行。
  const firstRow = rows.first()
  const installAction = firstRow.getByRole('button', { name: /^安装/ })
  const [rowBox, actionBox] = await Promise.all([firstRow.boundingBox(), installAction.boundingBox()])
  expect(rowBox).not.toBeNull()
  expect(actionBox).not.toBeNull()
  if (rowBox !== null && actionBox !== null) {
    expect(Math.abs(actionBox.x + actionBox.width - (rowBox.x + rowBox.width - 4))).toBeLessThanOrEqual(1)
    expect(Math.abs(actionBox.y + actionBox.height / 2 - (rowBox.y + rowBox.height / 2))).toBeLessThanOrEqual(1)
  }
  const pagination = panel.getByRole('navigation', { name: '插件分页', exact: true })
  await expect(pagination).toBeVisible()
  await pagination.getByRole('button', { name: '下一页', exact: true }).click()
  await expect(pagination.locator('.install-page-status')).toHaveText(/第 2 \/ \d+ 页/)
  const list = panel.locator('.install-list')
  expect(await list.evaluate((element) => getComputedStyle(element).overflowY)).toBe('auto')
  const body = dialog.locator('.agent-editor__body')
  expect(await body.evaluate((element) => getComputedStyle(element).overflowY)).toBe('hidden')
  expect(await body.evaluate((element) => element.scrollHeight - element.clientHeight)).toBeLessThanOrEqual(1)
  await page.setViewportSize({ width: 375, height: 720 })
  expect(await body.evaluate((element) => element.scrollWidth - element.clientWidth)).toBeLessThanOrEqual(1)
  expect(issues).toEqual([])
})

