test.use({ locale: 'zh-CN', reducedMotion: 'reduce' })
async function expectNoTabOverflow(page: Page): Promise<void> {
  const tabs = page.locator('.view-tabs')
  await expect(tabs).toBeVisible()
  expect(await tabs.evaluate((element) => element.scrollWidth - element.clientWidth)).toBeLessThanOrEqual(1)
}

const STATUS_WORDS = ['已连接', '需认证', '连接失败', '已停用', '插件已停用', '需配置', '连接中']
async function expectNoVisibleStatus(locator: Locator): Promise<void> {
  const text = await locator.evaluate((element) => {
    const clone = element.cloneNode(true)
    if (!(clone instanceof HTMLElement)) return ''
    clone.querySelectorAll('.mcp-visually-hidden').forEach((node) => node.remove())
    return clone.textContent ?? ''
  })
  for (const word of STATUS_WORDS) expect(text).not.toContain(word)
}

