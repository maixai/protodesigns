import { expect, test } from '@playwright/test'
import type { Page, Locator } from '@playwright/test'
import { collectRuntimeIssues, login, waitForWorkspace } from './helpers'
test.use({ locale: 'zh-CN', reducedMotion: 'reduce' })
async function openProjectMcp(page: Page): Promise<{ dialog: Locator; panel: Locator }> {
  await page.locator('.project-item').first().locator('.project-menu__trigger').click()
  await page.getByRole('menuitem', { name: '项目设置：weekly-report', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '项目设置 · weekly-report', exact: true })
  await dialog.getByRole('tab', { name: 'MCP', exact: true }).click()
  const panel = dialog.locator('.project-mcp')
  await expect(panel.locator('.project-mcp__server[data-source="project"]')).toHaveCount(3)
  await expect(panel.locator('.project-mcp__server[data-source="agent"]')).toHaveCount(4)
  return { dialog, panel }
}

test('@area:project-mcp 四标签承载三类 MCP 来源;同名两行并存,停用不回退', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await login(page); await waitForWorkspace(page)
  const { dialog, panel } = await openProjectMcp(page)
  await expect(dialog.locator('.project-settings__tablist').getByRole('tab')).toHaveText(['模型', '权限', '插件', 'MCP'])
  await expect(panel.locator('[data-source="plugin"]')).toContainText('Browser Automation')
  const inherited = panel.locator('.project-mcp__server[data-server-id="agent:planning:github"]')
  const own = panel.locator('.project-mcp__server[data-server-id="project:~/work/weekly-report:github"]')
  await expect(inherited).toContainText('被遮蔽 · 不生效')
  await expect(inherited.getByRole('switch')).toHaveCount(0)
  await expect(own).toContainText('替代 Agent 同名')
  await own.getByRole('switch').click()
  await expect(own).toContainText('本项目已停用')
  await expect(inherited).toHaveAttribute('data-effective', 'false')
  await expect(own).not.toContainText('停用不会回退到 Agent 版本')
  await own.locator('.project-mcp__main').click()
  await expect(panel.locator('.mcp-nofallback')).toContainText('停用不会回退到 Agent 版本')
  await panel.getByRole('button', { name: '返回 MCP', exact: true }).click()
  await expect(dialog.locator('.project-config__buttons .dl-btn--primary')).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
})

test('@area:project-mcp 项目 MCP 详情保存、Esc 草稿防丢与窗体关闭确认各守一层', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await login(page); await waitForWorkspace(page)
  const { dialog, panel } = await openProjectMcp(page)
  const github = panel.locator('.project-mcp__main[data-server-id="project:~/work/weekly-report:github"]')
  await github.click()
  await panel.getByLabel('显示名称', { exact: true }).fill('GitHub Project')
  await expect(dialog.getByRole('tab', { name: 'MCP · 有未保存的更改', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(panel.locator('.project-mcp__confirm')).toContainText('放弃未保存的更改')
  await expect(dialog).toBeVisible()
  await panel.getByRole('button', { name: '继续编辑', exact: true }).click()
  await panel.getByRole('button', { name: '保存更改', exact: true }).click()
  await expect(github).toContainText('GitHub Project')
  await expect(dialog.getByRole('tab', { name: 'MCP', exact: true })).toBeVisible()
  await github.click()
  await panel.getByLabel('显示名称', { exact: true }).fill('Unsaved name')
  await dialog.getByRole('button', { name: '关闭', exact: true }).click()
  const confirm = page.getByRole('alertdialog', { name: '有未保存的更改', exact: true })
  await expect(confirm).toContainText('MCP')
  await confirm.getByRole('button', { name: '放弃更改并关闭', exact: true }).click()
  await expect(dialog).toBeHidden()
})

test('@area:project-mcp 新增服务器在详情保存即生效,插件管理入口落到项目插件详情', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await login(page); await waitForWorkspace(page)
  const { dialog, panel } = await openProjectMcp(page)
  await panel.getByRole('button', { name: '添加 MCP 服务器', exact: true }).click()
  await panel.getByLabel('服务器名称', { exact: true }).fill('linear')
  await panel.getByLabel('命令', { exact: true }).fill('npx')
  await panel.getByRole('button', { name: '添加服务器', exact: true }).click()
  await expect(panel.locator('.project-mcp__server[data-source="project"]')).toHaveCount(4)
  await panel.locator('[data-plugin-id="browser-tools"]').getByRole('button').click()
  await expect(panel.locator('.mcp-readonly-badge')).toHaveText('由插件提供 · 只读')
  await expect(panel.locator('.mcp-server-editor')).toHaveCount(0)
  await panel.locator('.mcp-manage-plugin').click()
  const plugins = dialog.locator('.project-plugins')
  await expect(plugins.locator('.plugin-detail')).toContainText('Browser Tools')
  await expect(plugins.locator('.plugin-readonly')).toContainText('定义由 Agent 管理')
})

test('@area:project-mcp 项目 MCP 在四档视口无横向溢出且无运行错误', async ({ page }) => {
  const issues = collectRuntimeIssues(page)
  await page.setViewportSize({ width: 1280, height: 900 })
  await login(page); await waitForWorkspace(page)
  const { dialog } = await openProjectMcp(page)
  for (const width of [375, 768, 1280, 1600]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await dialog.evaluate((element) => element.scrollWidth - element.clientWidth)).toBeLessThanOrEqual(1)
  }
  expect(issues).toEqual([])
})


test('@area:project-mcp Agent 覆盖恢复留在详情,插件来源可折叠且只读', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await login(page); await waitForWorkspace(page)
  const { panel } = await openProjectMcp(page)
  const sentry = panel.locator('.project-mcp__server[data-server-id="agent:planning:sentry"]')
  await sentry.getByRole('switch').click()
  await expect(sentry).toContainText('本项目已停用')
  await expect(sentry.getByRole('button', { name: '恢复为 Agent 设置', exact: true })).toHaveCount(0)
  await sentry.locator('.project-mcp__main').click()
  await expect(panel.locator('.mcp-detail-status')).toContainText('覆盖')
  await expect(panel.locator('.mcp-server-editor')).toHaveCount(0)
  await panel.getByRole('button', { name: '为本项目「weekly-report」恢复「Sentry」的 Agent 设置', exact: true }).click()
  await expect(panel.locator('.mcp-detail-status')).toContainText('本项目已启用')
  await expect(panel.locator('.mcp-detail-status')).not.toContainText('覆盖')
  await panel.getByRole('button', { name: '返回 MCP', exact: true }).click()
  await expect(sentry.getByRole('switch')).toHaveAttribute('aria-checked', 'true')
  const disclosure = panel.locator('.mcp-plugin-disclosure')
  await disclosure.click()
  await expect(disclosure).toHaveAttribute('aria-expanded', 'false')
  await expect(panel.locator('.mcp-plugin-main').first()).toBeHidden()
  await disclosure.click()
  await expect(panel.locator('.mcp-plugin-main').first()).toBeVisible()
  await expect(panel.locator('.project-mcp__plugin [role="switch"]')).toHaveCount(0)
})
